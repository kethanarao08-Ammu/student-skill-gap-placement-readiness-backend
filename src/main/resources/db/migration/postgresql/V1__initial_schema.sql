CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE job_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    description TEXT,
    category VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_job_roles_title UNIQUE (title)
);

CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_skills_name UNIQUE (name)
);

CREATE TABLE student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    college VARCHAR(150),
    degree VARCHAR(100),
    branch VARCHAR(100),
    graduation_year INTEGER,
    cgpa NUMERIC(3, 2),
    phone VARCHAR(20),
    bio TEXT,
    target_job_role_id BIGINT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_student_profiles_user_id UNIQUE (user_id),
    CONSTRAINT fk_student_profiles_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_student_profiles_target_job_role
        FOREIGN KEY (target_job_role_id) REFERENCES job_roles (id)
);

CREATE TABLE student_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    student_profile_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    proficiency_level INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_student_skills_user_skill UNIQUE (user_id, skill_id),
    CONSTRAINT fk_student_skills_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_student_skills_profile
        FOREIGN KEY (student_profile_id) REFERENCES student_profiles (id),
    CONSTRAINT fk_student_skills_skill
        FOREIGN KEY (skill_id) REFERENCES skills (id)
);

CREATE TABLE student_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    student_profile_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    technologies VARCHAR(255),
    technologies_used VARCHAR(255) NOT NULL,
    project_url VARCHAR(255),
    github_url VARCHAR(255),
    start_date DATE,
    end_date DATE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_student_projects_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_student_projects_profile
        FOREIGN KEY (student_profile_id) REFERENCES student_profiles (id)
);

CREATE TABLE job_role_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_role_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    required_level INTEGER NOT NULL,
    required_proficiency INTEGER NOT NULL,
    importance_weight INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_job_role_skills_role_skill UNIQUE (job_role_id, skill_id),
    CONSTRAINT fk_job_role_skills_job_role
        FOREIGN KEY (job_role_id) REFERENCES job_roles (id),
    CONSTRAINT fk_job_role_skills_skill
        FOREIGN KEY (skill_id) REFERENCES skills (id)
);

CREATE TABLE learning_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    topic VARCHAR(100) NOT NULL,
    url VARCHAR(255) NOT NULL,
    resource_type VARCHAR(50) NOT NULL,
    platform VARCHAR(100) NOT NULL,
    estimated_duration VARCHAR(50) NOT NULL,
    difficulty_level VARCHAR(20) NOT NULL,
    CONSTRAINT fk_learning_resources_skill
        FOREIGN KEY (skill_id) REFERENCES skills (id)
);

CREATE TABLE learning_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    student_profile_id BIGINT NOT NULL,
    job_role_id BIGINT,
    skill_id BIGINT NOT NULL,
    priority VARCHAR(20) NOT NULL,
    reason TEXT NOT NULL,
    suggested_topic VARCHAR(150) NOT NULL,
    resource_title VARCHAR(200) NOT NULL,
    resource_url VARCHAR(255) NOT NULL,
    estimated_duration VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_learning_recommendations_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_learning_recommendations_profile
        FOREIGN KEY (student_profile_id) REFERENCES student_profiles (id),
    CONSTRAINT fk_learning_recommendations_job_role
        FOREIGN KEY (job_role_id) REFERENCES job_roles (id),
    CONSTRAINT fk_learning_recommendations_skill
        FOREIGN KEY (skill_id) REFERENCES skills (id)
);

CREATE TABLE certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    student_profile_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    title VARCHAR(150) NOT NULL,
    issuing_organization VARCHAR(150) NOT NULL,
    issue_date DATE NOT NULL,
    credential_url VARCHAR(255),
    certificate_id VARCHAR(100),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_certifications_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_certifications_profile
        FOREIGN KEY (student_profile_id) REFERENCES student_profiles (id)
);

CREATE TABLE assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    category VARCHAR(50) NOT NULL,
    total_questions INTEGER NOT NULL,
    time_limit_minutes INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE TABLE assessment_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL,
    question_text TEXT NOT NULL,
    category VARCHAR(50) NOT NULL,
    explanation TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_assessment_questions_assessment
        FOREIGN KEY (assessment_id) REFERENCES assessments (id)
);

CREATE TABLE assessment_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL,
    option_text VARCHAR(255) NOT NULL,
    option_letter VARCHAR(2) NOT NULL,
    is_correct BOOLEAN NOT NULL,
    CONSTRAINT fk_assessment_options_question
        FOREIGN KEY (question_id) REFERENCES assessment_questions (id)
);

CREATE TABLE assessment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    student_profile_id BIGINT NOT NULL,
    assessment_id BIGINT NOT NULL,
    total_score INTEGER NOT NULL,
    max_score INTEGER NOT NULL,
    percentage NUMERIC(5, 2) NOT NULL,
    readiness_level VARCHAR(50) NOT NULL,
    passed BOOLEAN NOT NULL,
    score_percentage NUMERIC(5, 2) NOT NULL,
    total_questions INTEGER NOT NULL,
    correct_answers INTEGER NOT NULL,
    readiness_category VARCHAR(50) NOT NULL,
    attempted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_assessment_attempts_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_assessment_attempts_profile
        FOREIGN KEY (student_profile_id) REFERENCES student_profiles (id),
    CONSTRAINT fk_assessment_attempts_assessment
        FOREIGN KEY (assessment_id) REFERENCES assessments (id)
);

CREATE TABLE assessment_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    selected_option_id BIGINT,
    is_correct BOOLEAN NOT NULL,
    marks_awarded INTEGER NOT NULL,
    CONSTRAINT fk_assessment_responses_attempt
        FOREIGN KEY (attempt_id) REFERENCES assessment_attempts (id),
    CONSTRAINT fk_assessment_responses_question
        FOREIGN KEY (question_id) REFERENCES assessment_questions (id),
    CONSTRAINT fk_assessment_responses_selected_option
        FOREIGN KEY (selected_option_id) REFERENCES assessment_options (id)
);
